// Writes docs/nodes.js: the prestige tree's node ids with their names, so the dashboard can label them.
// Run it again whenever the game's tree changes:   node tools/nodes.cjs ../smeltworks-idle
const path = require("path"), fs = require("fs");
const game = path.resolve(process.argv[2] || "../smeltworks-idle");
const { load } = require(path.join(game, "tests/harness.cjs"));
const SW = load(1), D = SW.data, G = SW.game, out = {};
for (const n of D.TREE) {
	const E = D.TREE_EFF[n.eff];
	out[n.id] = { n: E.name, t: typeof E.text === "function" ? E.text(n.amt, n) : String(E.text || ""), c: G.nodeCost(n.id), big: n.big ? 1 : 0 };
}
const file = path.join(__dirname, "../docs/nodes.js");
fs.writeFileSync(file, `// Generated by tools/nodes.cjs from Smeltworks Idle v${D.VERSION}: do not edit by hand.\n// id -> n: name, t: what it does, c: its price in cores, big: a notable or hub\nconst NODES = ${JSON.stringify(out, null, 1).replace(/\n\s+"(n|t|c|big)"/g, ' "$1"').replace(/\n\s+\}/g, " }")};\n`);
console.log(`${Object.keys(out).length} nodes -> ${path.relative(process.cwd(), file)}`);
